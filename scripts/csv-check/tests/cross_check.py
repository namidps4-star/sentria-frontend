#!/usr/bin/env python3
"""Runs the backend's check_upload and the checker on the same files and compares them.

    SENTRIA_BACKEND=/path/to/Sentria python3 scripts/csv-check/tests/cross_check.py \
        --write docs/csv-backend-cross-check.md

Compared per case and per language (fr, en): error_code, message, missing,
expected and looks_like. A case is "same" only when all five are equal.
test_cross_check.py fails on any difference, and when the saved table is stale.
"""
import argparse
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import support  # noqa: E402
from support import DATA, TABLE, check, sample_header_row, write_rows  # noqa: E402

FIELDS = ("error_code", "message", "missing", "expected", "looks_like")


def label(key):
    return f"{key[0]}/{key[1] or 'default'}"


def cases():
    out = []
    for key, entry in TABLE.items():
        sector, bt = key
        header, row = sample_header_row(entry)
        out.append((f"{label(key)}: sample", sector, bt, None, header, [row]))
        for group in entry["required"]:
            present = [n for n in group if n in entry["sample"]]
            h, r = sample_header_row(entry, drop=present)
            out.append((f"{label(key)}: missing {' or '.join(group)}", sector, bt, None, h, [r]))
        out.append((f"{label(key)}: header only", sector, bt, None, header, []))
        blank = [row[0]] + [""] * (len(row) - 1)
        out.append((f"{label(key)}: only the first column filled", sector, bt, None, header, [blank]))
        if [sector, bt] in DATA["single_store"]:
            h2, r2 = header + ["store_id"], None
            out.append((f"{label(key)}: two stores", sector, bt, None, h2, [row + ["S1"], row + ["S2"]]))
    supplier = ["order_date", "received_date", "product_name"]
    out.append(("supplier orders for health/pharmacie", "health", "pharmacie", None, supplier, [["2026-01-01", "2026-01-03", "x"]]))
    out.append(("supplier orders for retail/default", "retail", None, None, supplier, [["2026-01-01", "2026-01-03", "x"]]))
    out.append(("unknown sector, any columns", "nowhere", None, None, ["a", "b"], [["1", "2"]]))
    out.append(("unknown business type, falls back to the sector default", "health", "no-such-type", None,
                ["medicine_name", "stock_qty"], [["A", "3"]]))
    out.append(("unknown business type, falls back, columns missing", "health", "no-such-type", None, ["a"], [["1"]]))
    out.append(("logistics ops_type transport, truck columns", "logistics", None, "transport",
                ["truck_id", "mileage_km"], [["T1", "1000"]]))
    out.append(("logistics ops_type transport, equipment columns", "logistics", None, "transport",
                ["equipment_id", "daily_cycles"], [["E1", "4"]]))
    out.append(("retail/default with another department's columns", "retail", None, None,
                ["medicine_name", "stock_qty"], [["A", "3"]]))
    out.append(("one-shop fallback, unknown type, two stores (no store rule)", "retail", "no-such-type", None,
                ["product_name", "store_id", "stock_qty"], [["x", "S1", "3"], ["x", "S2", "3"]]))
    return out


def normalise(error):
    return None if error is None else {f: error.get(f) for f in FIELDS}


def outcome(error):
    return "accepted" if error is None else error["error_code"]


def compare(uc, alerts, tmp):
    rows = []
    for name, sector, bt, ops, header, body in cases():
        path = write_rows(os.path.join(tmp, "case.csv"), header, body)
        same, backend_out, checker_out = True, "", ""
        for lang in ("fr", "en"):
            ref = normalise(uc.check_upload(alerts.read_upload(path), sector, bt, ops, lang))
            got = normalise(check.evaluate(check.read_upload(path), DATA, sector, bt, ops, lang))
            same = same and ref == got
            backend_out, checker_out = outcome(ref), outcome(got)
        rows.append((name, backend_out, checker_out, same))
    return rows


def to_markdown(rows):
    different = [r for r in rows if not r[3]]
    lines = [
        "# CSV checker against the backend's check_upload",
        "",
        "Generated by `scripts/csv-check/tests/cross_check.py`. Do not edit by hand.",
        "",
        f"Specs exported from backend commit `{DATA['backend_commit']}`.",
        "Each case is built from the exported sample and run through the backend's `check_upload` (read with its own `read_upload`) and through `check.evaluate`, in French and in English. A case is the same only when `error_code`, `message`, `missing`, `expected` and `looks_like` are equal in both languages.",
        "",
        f"Cases: {len(rows)}. Differences: {len(different)}.",
        "",
        "| Case | Backend | Checker | Same |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {b} | {c} | {'yes' if s else 'NO'} |" for n, b, c, s in rows]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write")
    args = parser.parse_args()
    uc, alerts = support.backend("pipeline.upload_check"), support.backend("pipeline.alerts")
    if not uc or not alerts:
        print(support.SKIP_MESSAGE, file=sys.stderr)
        return 2
    with tempfile.TemporaryDirectory() as tmp:
        rows = compare(uc, alerts, tmp)
    text = to_markdown(rows)
    if args.write:
        with open(args.write, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"{len(rows)} cases, {sum(1 for r in rows if not r[3])} differences")
    return 0 if all(r[3] for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
