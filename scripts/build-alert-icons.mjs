// Writes lib/alert-icon-data.ts: the SVG of every icon in
// scripts/alert-icon-map.mjs, taken from the Fluent Emoji set installed as a
// dev dependency. The app ships only these few, with no request at run time.
import { writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { getIconData, iconToSVG } from "@iconify/utils"

import { ALERT_ICONS } from "./alert-icon-map.mjs"

const require = createRequire(import.meta.url)
const set = require("@iconify-json/fluent-emoji/icons.json")

const out = {}
for (const [name, id] of Object.entries(ALERT_ICONS)) {
  const data = getIconData(set, id)
  if (!data) throw new Error(`Missing icon ${id} (for ${name})`)
  const svg = iconToSVG(data)
  out[name] = { viewBox: svg.attributes.viewBox, body: svg.body, id }
}

const header = `// Generated by scripts/build-alert-icons.mjs from Fluent Emoji (Microsoft, MIT).
// Do not edit by hand: change scripts/alert-icon-map.mjs and run the script.
/* eslint-disable */
`
writeFileSync(
  new URL("../lib/alert-icon-data.ts", import.meta.url),
  header + "export const ALERT_ICON_DATA: Record<string, { viewBox: string; body: string; id: string }> = " + JSON.stringify(out, null, 1) + "\n"
)
console.log(`${Object.keys(out).length} alert icons written`)
